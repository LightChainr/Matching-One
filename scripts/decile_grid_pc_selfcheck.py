def check_c1() -> None:
    """HNF(2,1,2) should be a 2x2 grid folded with shear h21=1, h22=2.
    Verify by hand: cell = {(x,y): 0<=x<2, 0<=y<2}, fold maps (x, y) to
    ((x - k) mod 2, y mod 2) with k = (y - (y mod 2)) // 2 = 0 for y in {0,1}:
    here identity fold, so h21 shear has no effect at h22=2? No, k=0 for
    y in {0,1}, so the cell points are (0,0),(1,0),(0,1),(1,1). Verify
    (2,1) folds to (1,1) and (0,3) folds to (0,1)."""
    from decile_grid_pc_admissible_sweep import hnf_fold

    # lattice generated by (2,0) and (1,2); fold into {(x,y): 0<=x<2, 0<=y<2}.
    # (2,1) is NOT a lattice point (2k=1 impossible); fold keeps y=1, reduces
    # x mod 2 -> (0,1).  (0,3) is NOT a lattice point (2k=3); nearest lattice
    # offset k=1 shifts x by h21=1 -> (1,1).
    assert hnf_fold(0, 0, 2, 1, 2) == (0, 0)
    assert hnf_fold(2, 1, 2, 1, 2) == (0, 1), hnf_fold(2, 1, 2, 1, 2)
    assert hnf_fold(0, 3, 2, 1, 2) == (1, 1), hnf_fold(0, 3, 2, 1, 2)
    # (4,0) IS a lattice point (m=2,k=0) -> (0,0). (2,0) lattice point -> (0,0).
    assert hnf_fold(4, 0, 2, 1, 2) == (0, 0)
    assert hnf_fold(2, 0, 2, 1, 2) == (0, 0)
    print("C1 hnf_fold hand-grid checks: OK")


