def tilted_rates(
    generator: Generator, k: int, kind: str, epsilon: float
) -> Dict[Tuple[str, int], float]:
    """Baseline rates with the named part of the single-point tilt applied.

    ``H_single`` raises the join at point 0.  Its mirror under ``R`` is the join
    at ``(k-1) mod w``, so the even part raises both by half and the odd part
    raises one while lowering the other.  Writing the three as rate vectors keeps
    every tilted operator an exact generator, which uniformization needs.
    """

    partner = (k - 1) % generator.width
    rates = {move: 1.0 for move in generator.moves}
    if kind == "none":
        return rates
    if kind == "single":
        rates[("join", 0)] += epsilon
    elif kind == "even":
        rates[("join", 0)] += epsilon / 2
        rates[("join", partner)] += epsilon / 2
    elif kind == "odd":
        rates[("join", 0)] += epsilon / 2
        rates[("join", partner)] -= epsilon / 2
    else:  # pragma: no cover - guarded by the caller
        raise ValueError(f"unknown tilt {kind!r}")
    _require(all(rate >= 0.0 for rate in rates.values()), "tilt left the generator cone")
    return rates


def responses(
    generator: Generator, rates: Mapping[Tuple[str, int], float],
    readouts: Sequence[Tuple[str, Sequence[float]]],
    sources: Sequence[Tuple[str, Sequence[float]]],
) -> Dict[Tuple[str, str, float], float]:
    propagator = Propagator(generator.rows(rates), generator.size)
    out: Dict[Tuple[str, str, float], float] = {}
    for index, (readout_name, values) in enumerate(readouts):
        for t in LAGS:
            evolved = propagator.apply(index, values, t)
            for source_name, measure in sources:
                out[(source_name, readout_name, t)] = sum(
                    measure[i] * evolved[i] for i in range(generator.size)
                )
    return out


def second_order(generator: Generator, k: int, even_readouts: Sequence[str]) -> Dict[str, Any]:
    """Fit the order in ``eps`` at which the odd direction reaches an even task.

    Two differences are measured, and they say different things.  ``odd_vs_none``
    is the theorem itself: turning on the pure breaking direction must not move
    an invariant task at first order.  ``single_vs_even`` is the practical
    consequence for #580 -- the part of the observed intervention that destroyed
    the exact quotient is the part the task barely feels.
    """

    readouts = [
        (name, [function(state) for state in generator.states])
        for name, function in READOUTS if name in set(even_readouts)
    ]
    sources = source_distributions(generator)
    base = responses(generator, tilted_rates(generator, k, "none", 0.0), readouts, sources)

    series: Dict[str, List[Tuple[float, float]]] = {"odd_vs_none": [], "single_vs_even": []}
    for epsilon in EPSILONS:
        odd = responses(generator, tilted_rates(generator, k, "odd", epsilon), readouts, sources)
        even = responses(generator, tilted_rates(generator, k, "even", epsilon), readouts, sources)
        single = responses(generator, tilted_rates(generator, k, "single", epsilon), readouts, sources)
        scale = math.sqrt(sum(value * value for value in base.values()))
        series["odd_vs_none"].append((
            epsilon,
            math.sqrt(sum((odd[key] - base[key]) ** 2 for key in base)) / scale,
        ))
        series["single_vs_even"].append((
            epsilon,
            math.sqrt(sum((single[key] - even[key]) ** 2 for key in base)) / scale,
        ))

    out: Dict[str, Any] = {"readouts_scored": [name for name, _ in readouts]}
    for label, points in series.items():
        usable = [(e, d) for e, d in points if d > 0]
        if len(usable) >= 2:
            (e0, d0), (e1, d1) = usable[0], usable[-1]
            slope = math.log(d1 / d0) / math.log(e1 / e0)
        else:
            slope = float("nan")
        out[label] = {
            "points": [{"epsilon": e, "relative_difference": d} for e, d in points],
            "log_log_slope": slope,
            "consistent_with_second_order": bool(abs(slope - 2.0) < 0.15),
        }
    # A first-order control: the even part is *not* invisible, so its own slope
    # must be 1.  Without this the second-order fits could be measuring a bug
    # that makes every difference small.
    first_order = []
    for epsilon in EPSILONS:
        even = responses(generator, tilted_rates(generator, k, "even", epsilon), readouts, sources)
        scale = math.sqrt(sum(value * value for value in base.values()))
        first_order.append((
            epsilon,
            math.sqrt(sum((even[key] - base[key]) ** 2 for key in base)) / scale,
        ))
    (e0, d0), (e1, d1) = first_order[0], first_order[-1]
    out["even_vs_none"] = {
        "points": [{"epsilon": e, "relative_difference": d} for e, d in first_order],
        "log_log_slope": math.log(d1 / d0) / math.log(e1 / e0) if d0 > 0 and d1 > 0 else float("nan"),
        "consistent_with_first_order": bool(
            d0 > 0 and d1 > 0 and abs(math.log(d1 / d0) / math.log(e1 / e0) - 1.0) < 0.15
        ),
    }
    return out


