def apply_permutation(state: Sequence[int], permutation: Sequence[int]) -> Tuple[int, ...]:
    """Relabel a connectivity state by moving point ``i`` to ``permutation[i]``."""

    width = len(state)
    inverse = [0] * width
    for source, destination in enumerate(permutation):
        inverse[destination] = source
    return canonical_rgs([state[inverse[j]] for j in range(width)])


def rotation(width: int, k: int) -> List[int]:
    return [(i + k) % width for i in range(width)]


def reflection(width: int, k: int) -> List[int]:
    """The reflection ``i -> k - i`` of the cycle."""

    return [(k - i) % width for i in range(width)]


def state_permutation(generator: Generator, permutation: Sequence[int]) -> List[int]:
    """The induced permutation of state indices."""

    rank = {state: index for index, state in enumerate(generator.states)}
    return [rank[apply_permutation(state, permutation)] for state in generator.states]


def is_involution(pi: Sequence[int]) -> bool:
    return all(pi[pi[i]] == i for i in range(len(pi)))


def invariant_observable(
    generator: Generator, pi: Sequence[int], values: Sequence[float]
) -> bool:
    return all(values[pi[i]] == values[i] for i in range(generator.size))


