#!/usr/bin/env python3
"""#598 Phase A/B: the symmetry-breaking direction is first-order invisible.

#580 reported that a localized out-of-pencil tilt (``single_point_join``)
destroys P398's exact positive lumping at every width -- the coarsest admissible
partition collapses to the identity -- while #580/#588 found the frozen
finite-horizon input/output description barely moves.  That contrast was written
up as "the positive state is fragile".  #598 proposes a much better explanation,
and this script tests it exactly.

The proposal has two halves.

**Half one: the positive block count is an orbit count.**  The reported
``r_positive = 10, 26, 76, 232, 750`` for widths 4-8 equals

    r_reflect(w) = [ Catalan(w) + binom(w, floor(w/2)) ] / 2,

which is Burnside's count for the group generated by a single reflection.  This
script verifies that arithmetic *and* the fact that makes it much weaker than it
looks: **every** reflection of the cycle fixes exactly ``binom(w, floor(w/2))``
noncrossing states, so the count alone does not identify which reflection.  The
identification has to come from the task, and it does: exactly one reflection
preserves the declared dictionary at every width.

**Half two: a parity selection rule.**  With ``R`` that reflection, write

    H_single = H_even + H_odd,
    H_even = (H_single + R H_single R)/2,
    H_odd  = (H_single - R H_single R)/2.

If the baseline generator is ``R``-equivariant and the declared source ``mu`` and
readout ``f`` are ``R``-even, then the first-order response to ``H_odd`` vanishes
*pointwise in the time integrand*, not merely on average:

    mu^T e^{(t-s)G} H_odd e^{sG} f = 0   for every 0 <= s <= t,

because ``e^{sG}f`` stays even, ``H_odd`` maps even to odd, and an even measure
annihilates an odd function.  So an exact quotient can be destroyed by an
arbitrarily small intervention while every invariant finite-horizon task stays
blind to the breaking direction at ``O(eps)``.

This is checked as a chain of exact sector statements rather than by
differentiating an exponential, which makes it a theorem test instead of a
numerical coincidence.  Phase B then confirms the consequence empirically: for
even tasks the gap between the full tilt and its even part must be ``O(eps^2)``.

The test can fail, and one built-in case shows how: ``halves_linked`` is *not*
``R``-even at odd widths, so at ``w = 5`` and ``w = 7`` its first-order response
to ``H_odd`` is required to be nonzero.  A run in which everything vanishes is a
broken test, not a stronger theorem.
"""

