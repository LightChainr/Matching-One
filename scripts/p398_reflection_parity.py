def exact_rows(
    generator: Generator, rates: Mapping[Tuple[str, int], Fraction]
) -> List[Dict[int, Fraction]]:
    """Row-oriented operator in exact rational arithmetic."""

    out: List[Dict[int, Fraction]] = []
    for source in range(generator.size):
        entries: Dict[int, Fraction] = {}
        diagonal = Fraction(0)
        for move, rate in rates.items():
            image = generator.target[move][source]
            if image is None or rate == 0:
                continue
            entries[image] = entries.get(image, Fraction(0)) + rate
            diagonal -= rate
        if diagonal != 0:
            entries[source] = entries.get(source, Fraction(0)) + diagonal
        out.append({key: value for key, value in entries.items() if value != 0})
    return out


def conjugate(rows: Sequence[Mapping[int, Fraction]], pi: Sequence[int]) -> List[Dict[int, Fraction]]:
    """``R K R`` for a permutation ``R``: entry ``(i,j)`` becomes ``(pi[i], pi[j])``."""

    out: List[Dict[int, Fraction]] = [dict() for _ in rows]
    for source, row in enumerate(rows):
        target = out[pi[source]]
        for destination, value in row.items():
            target[pi[destination]] = value
    return out


def rows_equal(
    left: Sequence[Mapping[int, Fraction]], right: Sequence[Mapping[int, Fraction]]
) -> bool:
    return all(dict(a) == dict(b) for a, b in zip(left, right))


def combine_rows(
    left: Sequence[Mapping[int, Fraction]],
    right: Sequence[Mapping[int, Fraction]],
    sign: int,
) -> List[Dict[int, Fraction]]:
    out = []
    for a, b in zip(left, right):
        merged = dict(a)
        for key, value in b.items():
            merged[key] = merged.get(key, Fraction(0)) + sign * value
        out.append({key: value / 2 for key, value in merged.items() if value != 0})
    return out


def frobenius_rows(rows: Sequence[Mapping[int, Fraction]]) -> float:
    return math.sqrt(float(sum(value * value for row in rows for value in row.values())))


def move_indicator(generator: Generator, operation: str, point: int) -> Dict[Tuple[str, int], Fraction]:
    return {
        move: (Fraction(1) if move == (operation, point) else Fraction(0))
        for move in generator.moves
    }


def equivariance(generator: Generator, k: int) -> Dict[str, Any]:
    """Exact ``R K R = K`` for the pencil, and the move-level reason.

    The operator identity is the thing the theorem needs, but the *reason* is
    worth recording separately: ``R`` maps the join at point ``p`` to the join at
    ``(k-1) - p`` and the detach at ``p`` to the detach at ``k - p``.  Uniform
    sums over ``p`` are therefore invariant, and a single-point tilt is not --
    which is the whole asymmetry between the declared pencil and ``H_single``.
    """

    width = generator.width
    pi = state_permutation(generator, reflection(width, k))
    joins = {move: (Fraction(1) if move[0] == "join" else Fraction(0)) for move in generator.moves}
    detaches = {move: (Fraction(1) if move[0] == "detach" else Fraction(0)) for move in generator.moves}
    baseline = {move: Fraction(1) for move in generator.moves}

    results = {}
    for name, rates in (("J", joins), ("D", detaches), ("G0", baseline)):
        rows = exact_rows(generator, rates)
        results[f"R_{name}_R_equals_{name}"] = rows_equal(conjugate(rows, pi), rows)

    # Move-level witness, exact and independent of the operator identity above.
    move_map = []
    for point in range(width):
        for operation, expected in (
            ("join", (k - 1 - point) % width),
            ("detach", (k - point) % width),
        ):
            rows = exact_rows(generator, move_indicator(generator, operation, point))
            image = exact_rows(generator, move_indicator(generator, operation, expected))
            move_map.append({
                "move": f"{operation}@{point}",
                "predicted_image": f"{operation}@{expected}",
                "conjugation_matches": rows_equal(conjugate(rows, pi), image),
            })
    results["move_conjugation"] = move_map
    results["all_moves_map_as_predicted"] = all(row["conjugation_matches"] for row in move_map)
    results["reflection_is_state_involution"] = is_involution(pi)
    return results


def parity_split(generator: Generator, k: int) -> Dict[str, Any]:
    """Split the single-point tilt into ``R``-even and ``R``-odd parts, exactly."""

    width = generator.width
    pi = state_permutation(generator, reflection(width, k))
    single = exact_rows(generator, move_indicator(generator, "join", 0))
    mirrored = conjugate(single, pi)
    even = combine_rows(single, mirrored, +1)
    odd = combine_rows(single, mirrored, -1)

    # The mirrored tilt should be the join at (k-1) - 0, checked independently.
    partner_point = (k - 1) % width
    partner = exact_rows(generator, move_indicator(generator, "join", partner_point))

    sum_back = [
        {key: value for key, value in
         {**{d: even[i].get(d, Fraction(0)) + odd[i].get(d, Fraction(0))
             for d in set(even[i]) | set(odd[i])}}.items() if value != 0}
        for i in range(generator.size)
    ]
    return {
        "mirror_partner_point": partner_point,
        "mirrored_single_is_the_partner_join": rows_equal(mirrored, partner),
        "R_Heven_R_equals_plus_Heven": rows_equal(conjugate(even, pi), even),
        "R_Hodd_R_equals_minus_Hodd": rows_equal(
            conjugate(odd, pi), [{d: -v for d, v in row.items()} for row in odd]
        ),
        "even_plus_odd_is_H_single": rows_equal(sum_back, single),
        "norm_H_single": frobenius_rows(single),
        "norm_H_even": frobenius_rows(even),
        "norm_H_odd": frobenius_rows(odd),
        "odd_share_of_norm": (
            frobenius_rows(odd) / frobenius_rows(single) if frobenius_rows(single) > 0 else 0.0
        ),
        "_even": even,
        "_odd": odd,
    }


# --------------------------------------------------------------------------
# The selection rule, checked pointwise in the time integrand
# --------------------------------------------------------------------------


def rows_to_float(rows: Sequence[Mapping[int, Fraction]]) -> List[List[Tuple[int, float]]]:
    return [sorted((key, float(value)) for key, value in row.items()) for row in rows]


def transpose_rows(
    rows: Sequence[Sequence[Tuple[int, float]]], size: int
) -> List[List[Tuple[int, float]]]:
    gathered: List[Dict[int, float]] = [dict() for _ in range(size)]
    for source, row in enumerate(rows):
        for destination, value in row:
            gathered[destination][source] = gathered[destination].get(source, 0.0) + value
    return [sorted(entry.items()) for entry in gathered]


class Propagator:
    """``exp(t A) v`` by uniformization, with the ``P^k v`` sequence cached.

    The cache is the reason the whole (s, t) grid is affordable at width 8: the
    Krylov-like sequence depends only on the vector, so every time on the grid is
    a reweighting of one sequence rather than a fresh matrix-exponential.
    """

    def __init__(self, rows: Sequence[Sequence[Tuple[int, float]]], size: int) -> None:
        # Uniformization rate: the largest exit rate, i.e. the most negative
        # diagonal entry.  Taking a larger rate is always safe (it only adds
        # Poisson terms); taking a smaller one would make ``I + A/rate`` have
        # negative entries and the series would stop being a probabilistic
        # average, which is what keeps it numerically stable.
        rate = 0.0
        for source, row in enumerate(rows):
            for column, value in row:
                if column == source:
                    rate = max(rate, -value)
        self.rate = rate if rate > 0 else 1.0
        self.size = size
        self.rows = rows
        self._cache: Dict[int, List[List[float]]] = {}

    def _sequence(self, key: int, vector: Sequence[float], terms: int) -> List[List[float]]:
        cached = self._cache.get(key)
        if cached is not None and len(cached) >= terms:
            return cached
        sequence = [list(vector)]
        current = list(vector)
        for _ in range(terms - 1):
            stepped = matvec(self.rows, current)
            current = [
                current[i] + stepped[i] / self.rate for i in range(self.size)
            ]
            sequence.append(current)
        self._cache[key] = sequence
        return sequence

    def terms_for(self, time: float) -> int:
        mean = self.rate * time
        terms, mass, weight = 1, math.exp(-mean), math.exp(-mean)
        while mass < 1.0 - POISSON_TAIL and terms < MAX_POISSON:
            weight *= mean / terms
            mass += weight
            terms += 1
        return terms + 1

    def apply(self, key: int, vector: Sequence[float], time: float) -> List[float]:
        if time == 0.0:
            return list(vector)
        terms = self.terms_for(time)
        sequence = self._sequence(key, vector, terms)
        mean = self.rate * time
        out = [0.0] * self.size
        weight = math.exp(-mean)
        for k in range(min(terms, len(sequence))):
            if weight > 0.0:
                row = sequence[k]
                for i in range(self.size):
                    out[i] += weight * row[i]
            weight *= mean / (k + 1)
        return out


def _relative(defect: Sequence[float], reference: Sequence[float]) -> float:
    scale = math.sqrt(sum(value * value for value in reference))
    if scale == 0.0:
        return 0.0
    return math.sqrt(sum(value * value for value in defect)) / scale


def parity_defect(vector: Sequence[float], pi: Sequence[int], sign: int) -> float:
    """How far ``vector`` is from the ``sign`` eigenspace of ``R``, relatively."""

    defect = [vector[i] - sign * vector[pi[i]] for i in range(len(vector))]
    return _relative(defect, vector) / 2


def selection_rule(
    generator: Generator, k: int, odd_rows: Sequence[Mapping[int, Fraction]]
) -> Dict[str, Any]:
    """The pointwise integrand ``mu^T e^{(t-s)G} H_odd e^{sG} f`` over the grid.

    Checked pointwise rather than after integration on purpose: the theorem says
    every integrand vanishes, so a quadrature that happened to cancel would be a
    weaker and more accident-prone confirmation.  Each pair also reports the two
    sector facts the vanishing rests on, so a failure says *which* link broke.
    """

    pi = state_permutation(generator, reflection(generator.width, k))
    baseline = generator.rows({move: 1.0 for move in generator.moves})
    forward = Propagator(baseline, generator.size)
    backward = Propagator(transpose_rows(baseline, generator.size), generator.size)
    odd = rows_to_float(odd_rows)

    readouts = [
        (name, [function(state) for state in generator.states])
        for name, function in READOUTS
    ]
    sources = source_distributions(generator)

    readout_parity = {
        name: parity_defect(values, pi, +1) for name, values in readouts
    }
    source_parity = {
        name: parity_defect(vector, pi, +1) for name, vector in sources
    }

    rows = []
    for t in LAGS:
        for fraction in SPLIT_FRACTIONS:
            s = t * fraction
            evolved = {
                name: forward.apply(index, values, s)
                for index, (name, values) in enumerate(readouts)
            }
            tilted = {name: matvec(odd, vector) for name, vector in evolved.items()}
            measures = {
                name: backward.apply(1000 + index, vector, t - s)
                for index, (name, vector) in enumerate(sources)
            }
            for source_name, measure in measures.items():
                for readout_name, image in tilted.items():
                    value = sum(measure[i] * image[i] for i in range(generator.size))
                    scale = (
                        math.sqrt(sum(v * v for v in measure))
                        * math.sqrt(sum(v * v for v in image))
                    )
                    rows.append({
                        "t": t,
                        "s": s,
                        "source": source_name,
                        "readout": readout_name,
                        "integrand": value,
                        "relative_integrand": (value / scale) if scale > 0 else 0.0,
                        "evolved_readout_even_defect": parity_defect(
                            evolved[readout_name], pi, +1
                        ),
                        "tilted_odd_defect": parity_defect(image, pi, -1),
                        "evolved_source_even_defect": parity_defect(measure, pi, +1),
                    })

    even_readouts = {name for name, defect in readout_parity.items() if defect < SECTOR_TOLERANCE}
    even_sources = {name for name, defect in source_parity.items() if defect < SECTOR_TOLERANCE}
    protected = [
        row for row in rows
        if row["source"] in even_sources and row["readout"] in even_readouts
    ]
    exposed = [
        row for row in rows
        if row["source"] in even_sources and row["readout"] not in even_readouts
    ]
    return {
        "readout_even_defect": readout_parity,
        "source_even_defect": source_parity,
        "even_readouts": sorted(even_readouts),
        "odd_containing_readouts": sorted(set(readout_parity) - even_readouts),
        "even_sources": sorted(even_sources),
        "protected_pairs": len(protected),
        "worst_protected_relative_integrand": max(
            (abs(row["relative_integrand"]) for row in protected), default=0.0
        ),
        "protected_all_vanish": all(
            abs(row["relative_integrand"]) < SECTOR_TOLERANCE for row in protected
        ),
        "exposed_pairs": len(exposed),
        "largest_exposed_relative_integrand": max(
            (abs(row["relative_integrand"]) for row in exposed), default=0.0
        ),
        "exposed_channel_is_visible": any(
            abs(row["relative_integrand"]) > 1e-6 for row in exposed
        ),
        "worst_sector_defect": max(
            (max(row["evolved_readout_even_defect"], row["tilted_odd_defect"],
                 row["evolved_source_even_defect"])
             for row in rows if row["readout"] in even_readouts),
            default=0.0,
        ),
    }


