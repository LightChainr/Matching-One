def width_report(width: int) -> Dict[str, Any]:
    generator = Generator(width)
    survey = reflection_survey(generator)
    k = survey["task_compatible_k"]
    _require(k is not None, f"width {width}: the declared dictionary does not name one reflection")
    split = parity_split(generator, k)
    rule = selection_rule(generator, k, split["_odd"])
    report = {
        "width": width,
        "states": generator.size,
        "task_compatible_reflection": f"i -> {k} - i",
        "reflection_survey": {
            key: value for key, value in survey.items() if key != "by_reflection"
        },
        "per_reflection_fixed_states": {
            row["k"]: row["fixed_states"] for row in survey["by_reflection"]
        },
        "orbit_count": burnside_check(generator, k),
        "lumping": lumping_comparison(generator, k),
        "equivariance": {
            key: value for key, value in equivariance(generator, k).items()
            if key != "move_conjugation"
        },
        "parity_split": {key: value for key, value in split.items() if not key.startswith("_")},
        "selection_rule": rule,
        "second_order": second_order(generator, k, rule["even_readouts"]),
    }
    return report


def decide(reports: Sequence[Mapping[str, Any]]) -> Dict[str, Any]:
    orbit_ok = all(r["orbit_count"]["matches_reported_r_positive"] for r in reports)
    partition_ok = all(r["lumping"]["D0"]["coarsest_equals_orbit_partition"] for r in reports)
    equivariant = all(
        r["equivariance"]["R_G0_R_equals_G0"] and r["equivariance"]["all_moves_map_as_predicted"]
        for r in reports
    )
    split_ok = all(
        r["parity_split"]["R_Hodd_R_equals_minus_Hodd"]
        and r["parity_split"]["R_Heven_R_equals_plus_Heven"]
        and r["parity_split"]["even_plus_odd_is_H_single"]
        for r in reports
    )
    protected = all(r["selection_rule"]["protected_all_vanish"] for r in reports)
    # The test has to be able to fail somewhere, or its passing means nothing.
    exposed_seen = any(r["selection_rule"]["exposed_channel_is_visible"] for r in reports)
    second = all(r["second_order"]["odd_vs_none"]["consistent_with_second_order"] for r in reports)
    first = all(r["second_order"]["even_vs_none"]["consistent_with_first_order"] for r in reports)

    if not (equivariant and split_ok):
        verdict = "SETUP_FAILED__BASELINE_IS_NOT_EQUIVARIANT_OR_THE_SPLIT_IS_WRONG"
    elif not exposed_seen:
        verdict = "TEST_IS_VACUOUS__NO_ODD_CHANNEL_PRESENT_TO_FALSIFY_THE_RULE"
    elif not protected:
        verdict = "SELECTION_RULE_FAILS__AN_INVARIANT_TASK_RESPONDS_AT_FIRST_ORDER"
    elif not (second and first):
        verdict = "SELECTION_RULE_HOLDS_BUT_THE_ORDER_LADDER_DISAGREES"
    elif orbit_ok and partition_ok:
        verdict = "SYMMETRY_QUOTIENT_PLUS_PARITY_SELECTION_RULE__GATE1_BRANCH_A"
    elif orbit_ok:
        verdict = "ORBIT_COUNT_MATCHES_BUT_THE_PARTITION_DIFFERS__GATE1_BRANCH_B"
    else:
        verdict = "ORBIT_ACCOUNT_REJECTED__REPAIR_THE_STATE_SEMANTICS_FIRST"

    return {
        "orbit_count_matches_reported_r_positive": orbit_ok,
        "coarsest_lumping_is_the_orbit_partition": partition_ok,
        "baseline_is_R_equivariant": equivariant,
        "parity_split_is_exact": split_ok,
        "invariant_tasks_have_zero_first_order_response": protected,
        "an_odd_channel_exists_so_the_test_can_fail": exposed_seen,
        "odd_direction_enters_at_second_order": second,
        "even_direction_enters_at_first_order": first,
        "verdict": verdict,
        "predicted_r_positive": {
            width: (catalan(width) + math.comb(width, width // 2)) // 2
            for width in (9, 10)
        },
        "claim_boundary": (
            "This is an exact finite symmetry statement about P398, not a "
            "percolation-threshold result.  The reflection is not a continuum "
            "spin label, and the small balanced order remains task-relative.  "
            "The orbit-count identity alone identifies nothing -- every "
            "reflection gives the same count -- so the load is carried by the "
            "partition equality and the selection rule, not by the formula."
        ),
    }


def assemble(widths: Sequence[int]) -> Dict[str, Any]:
    reports = [width_report(width) for width in widths]
    return {
        "schema": SCHEMA,
        "issue": ISSUE,
        "status": "exact symmetry/parity computation; no sampling, no new width, no fit",
        "widths": list(widths),
        "declared": {
            "dictionary_D0": list(D0_NAMES),
            "held_out_readouts": [name for name, _ in HELD_OUT_READOUTS],
            "lags": list(LAGS),
            "split_fractions": list(SPLIT_FRACTIONS),
            "epsilons": list(EPSILONS),
            "sector_tolerance": SECTOR_TOLERANCE,
        },
        "by_width": reports,
        "decision": decide(reports),
    }


def render(payload: Mapping[str, Any]) -> str:
    lines = [f"#{ISSUE} P398 reflection parity: is the breaking direction first-order invisible?", ""]
    lines.append(
        f"  {'w':>2} {'states':>7} {'R':>12} {'orbits':>7} {'r_pos':>6} {'P=orbit':>8}"
        f" {'|Hodd|/|H|':>11} {'prot.':>6} {'worst':>10} {'exposed':>9}"
    )
    for report in payload["by_width"]:
        rule = report["selection_rule"]
        lines.append(
            f"  {report['width']:>2} {report['states']:>7}"
            f" {report['task_compatible_reflection']:>12}"
            f" {report['orbit_count']['orbits_counted']:>7}"
            f" {str(report['orbit_count']['reported_r_positive']):>6}"
            f" {str(report['lumping']['D0']['coarsest_equals_orbit_partition']):>8}"
            f" {report['parity_split']['odd_share_of_norm']:>11.4f}"
            f" {rule['protected_pairs']:>6}"
            f" {rule['worst_protected_relative_integrand']:>10.2e}"
            f" {rule['largest_exposed_relative_integrand']:>9.3f}"
        )
    lines += ["", "  order ladder on invariant tasks (log-log slope over the declared epsilon grid)", ""]
    lines.append(f"  {'w':>2} {'odd vs none':>12} {'single vs even':>15} {'even vs none':>13}")
    for report in payload["by_width"]:
        second = report["second_order"]
        lines.append(
            f"  {report['width']:>2} {second['odd_vs_none']['log_log_slope']:>12.4f}"
            f" {second['single_vs_even']['log_log_slope']:>15.4f}"
            f" {second['even_vs_none']['log_log_slope']:>13.4f}"
        )
    for report in payload["by_width"]:
        odd_names = report["selection_rule"]["odd_containing_readouts"]
        if odd_names:
            lines.append(
                f"  w={report['width']}: odd-containing readout(s) {odd_names} -- "
                f"first-order response required and observed at "
                f"{report['selection_rule']['largest_exposed_relative_integrand']:.3f}"
            )
    decision = payload["decision"]
    lines += [
        "",
        f"predicted r_positive at widths 9, 10: {decision['predicted_r_positive']}",
        f"VERDICT: {decision['verdict']}",
    ]
    return "\n".join(lines)


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--widths", type=int, nargs="+", default=list(DEFAULT_WIDTHS))
    parser.add_argument("--output", type=Path, default=DEFAULT_OUTPUT)
    args = parser.parse_args(argv)
    payload = assemble(tuple(args.widths))
    args.output.parent.mkdir(parents=True, exist_ok=True)
    args.output.write_text(json.dumps(payload, indent=2, default=float) + "\n", encoding="utf-8")
    print(render(payload))
    print()
    print(args.output)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
