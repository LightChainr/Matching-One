def catalan(width: int) -> int:
    return math.comb(2 * width, width) // (width + 1)


def orbit_count(pi: Sequence[int]) -> int:
    """Number of orbits of an involution, by Burnside: ``(|X| + |Fix|)/2``."""

    _require(is_involution(pi), "orbit_count expects an involution")
    fixed = sum(1 for i in range(len(pi)) if pi[i] == i)
    return (len(pi) + fixed) // 2


def reflection_survey(generator: Generator) -> Dict[str, Any]:
    """Fixed-point and orbit counts for every reflection, plus the task filter.

    Two separate facts come out of this, and conflating them would overstate the
    result.  First, *every* reflection has the same fixed-point count, so the
    Burnside match to ``r_positive`` is a necessary condition that identifies
    nothing.  Second, the declared dictionary is preserved by exactly one of
    them, and *that* is what names ``R``.
    """

    width = generator.width
    values = {
        name: [function(state) for state in generator.states]
        for name, function in READOUTS
    }
    sources = {name: vector for name, vector in source_distributions(generator)}

    rows = []
    d0_preserving = []
    all_preserving = []
    for k in range(width):
        pi = state_permutation(generator, reflection(width, k))
        _require(is_involution(pi), f"reflection {k} is not an involution on states")
        preserved = [name for name, _ in READOUTS if invariant_observable(generator, pi, values[name])]
        source_preserved = [
            name for name, vector in sources.items()
            if invariant_observable(generator, pi, vector)
        ]
        rows.append({
            "reflection": f"i -> {k} - i",
            "k": k,
            "fixed_states": sum(1 for i in range(generator.size) if pi[i] == i),
            "orbits": orbit_count(pi),
            "readouts_preserved": preserved,
            "sources_preserved": source_preserved,
        })
        if set(D0_NAMES) <= set(preserved):
            d0_preserving.append(k)
        if len(preserved) == len(READOUTS):
            all_preserving.append(k)

    central = math.comb(width, width // 2)
    return {
        "by_reflection": rows,
        "all_reflections_have_the_same_fixed_count": len({row["fixed_states"] for row in rows}) == 1,
        "central_binomial": central,
        "fixed_count_equals_central_binomial": all(
            row["fixed_states"] == central for row in rows
        ),
        "reflections_preserving_D0": d0_preserving,
        "reflections_preserving_all_readouts": all_preserving,
        "task_compatible_k": d0_preserving[0] if len(d0_preserving) == 1 else None,
    }


def burnside_check(generator: Generator, k: int) -> Dict[str, Any]:
    pi = state_permutation(generator, reflection(generator.width, k))
    width = generator.width
    formula = (catalan(width) + math.comb(width, width // 2)) // 2
    counted = orbit_count(pi)
    reported = REPORTED_R_POSITIVE.get(width)
    return {
        "catalan": catalan(width),
        "central_binomial": math.comb(width, width // 2),
        "r_reflect_formula": formula,
        "orbits_counted": counted,
        "formula_matches_count": formula == counted,
        "reported_r_positive": reported,
        "matches_reported_r_positive": reported is not None and reported == counted,
        "caveat": (
            "Every reflection gives this same orbit count, so agreement with "
            "r_positive is necessary and not identifying.  What names R is the "
            "declared dictionary, not this number.  Agreement here also does not "
            "show that the coarsest admissible lumping *is* the orbit partition "
            "-- only that the two have the same cardinality."
        ),
    }


# --------------------------------------------------------------------------
# The decisive Gate-1 comparison: is the coarsest lumping the orbit partition?
# --------------------------------------------------------------------------


def observable_partition(
    generator: Generator, names: Sequence[str]
) -> List[int]:
    """Initial partition: states agreeing on every named readout.

    Admissibility is not optional.  A lumping that merged two states the
    dictionary distinguishes could not carry the declared readouts, so the
    refinement has to start here rather than from the one-block partition.
    """

    lookup = dict(READOUTS)
    signature: Dict[Tuple[float, ...], int] = {}
    labels = []
    for state in generator.states:
        key = tuple(lookup[name](state) for name in names)
        if key not in signature:
            signature[key] = len(signature)
        labels.append(signature[key])
    return labels


def coarsest_lumping(
    generator: Generator,
    rate_sets: Sequence[Mapping[Tuple[str, int], float]],
    labels: Sequence[int],
) -> List[int]:
    """Coarsest strong lumping refining ``labels`` and stable for every rate set.

    Strong lumpability asks that for states ``i, j`` in one block and any block
    ``C``, the total rate into ``C`` agrees.  Requiring it for ``J`` and ``D``
    separately is the same as requiring it for the whole affine pencil, since
    ``G_eta`` is a linear combination of the two with the coefficients varying:
    a partition stable for two independent members of a two-dimensional pencil
    is stable for all of it.
    """

    labels = list(labels)
    operators = [generator.rows(rates) for rates in rate_sets]
    while True:
        signature: Dict[Tuple[Any, ...], int] = {}
        refined = []
        for source in range(generator.size):
            key: List[Any] = [labels[source]]
            for rows in operators:
                totals: Dict[int, float] = {}
                for destination, value in rows[source]:
                    block = labels[destination]
                    totals[block] = totals.get(block, 0.0) + value
                key.append(tuple(sorted(totals.items())))
            frozen = tuple(key)
            if frozen not in signature:
                signature[frozen] = len(signature)
            refined.append(signature[frozen])
        if refined == labels:
            return labels
        labels = refined


def canonical_labels(labels: Sequence[int]) -> Tuple[int, ...]:
    return canonical_rgs(list(labels))


def orbit_labels(generator: Generator, k: int) -> List[int]:
    pi = state_permutation(generator, reflection(generator.width, k))
    labels = [-1] * generator.size
    next_label = 0
    for i in range(generator.size):
        if labels[i] < 0:
            labels[i] = labels[pi[i]] = next_label
            next_label += 1
    return labels


def lumping_comparison(generator: Generator, k: int) -> Dict[str, Any]:
    """Compare the coarsest admissible lumping with the reflection-orbit partition.

    This is the question #596's Gate 1 actually asks, and cardinality does not
    answer it: two partitions with 750 blocks each need not be the same
    partition.  Because every admissible lumping refines the coarsest one, an
    orbit partition that is itself admissible and has the same block count must
    *be* the coarsest -- so equality here is decidable, not approximate.
    """

    baseline = {move: 1.0 for move in generator.moves}
    joins = {move: (1.0 if move[0] == "join" else 0.0) for move in generator.moves}
    detaches = {move: (1.0 if move[0] == "detach" else 0.0) for move in generator.moves}

    out: Dict[str, Any] = {}
    for label, names in (("D0", D0_NAMES), ("all_readouts", tuple(name for name, _ in READOUTS))):
        initial = observable_partition(generator, names)
        coarsest = coarsest_lumping(generator, (joins, detaches), initial)
        orbits = orbit_labels(generator, k)
        orbit_is_admissible = canonical_labels(
            coarsest_lumping(generator, (joins, detaches), orbits)
        ) == canonical_labels(orbits)
        out[label] = {
            "initial_blocks": len(set(initial)),
            "coarsest_blocks": len(set(coarsest)),
            "orbit_blocks": len(set(orbits)),
            "orbit_partition_is_admissible": orbit_is_admissible,
            "coarsest_equals_orbit_partition": canonical_labels(coarsest) == canonical_labels(orbits),
        }
    out["baseline_is_pencil_sum"] = all(
        baseline[move] == joins[move] + detaches[move] for move in generator.moves
    )
    return out


